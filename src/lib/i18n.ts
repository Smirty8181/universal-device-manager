export type Locale = "ru" | "en";

const saved = (() => {
  try {
    return (localStorage.getItem("udm.locale") as Locale) || "ru";
  } catch {
    return "ru";
  }
})();

export const locale = ref<Locale>(saved);

export function setLocale(next: Locale) {
  locale.value = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem("udm.locale", next);
  } catch {}
}

